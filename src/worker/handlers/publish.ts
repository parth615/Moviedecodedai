import { prisma } from '../../lib/prisma';
import { logToJob } from '../../lib/queue';
import { getSetting } from '../../lib/settings';
import { uploadToYouTube } from '../../lib/providers/youtube';
import path from 'path';

export async function handlePublishVideo(data: { videoId: string }, jobId: string) {
  const { videoId } = data;
  if (!videoId) throw new Error("Missing videoId");

  const video = await prisma.video.findUnique({ 
    where: { id: videoId },
    include: { script: { include: { topic: true } } }
  });

  if (!video) throw new Error(`Video ${videoId} not found`);

  // Double check approval
  const approval = await prisma.approval.findUnique({ where: { videoId } });
  if (approval?.status !== 'APPROVED') {
    throw new Error(`Cannot publish video ${videoId} because approval status is ${approval?.status}`);
  }

  await logToJob(jobId, `Starting Publishing process for video: ${video.id}`);
  
  const providerMode = await getSetting('PROVIDER_MODE');

  const absVideoPath = path.join(process.cwd(), 'public', video.fileUrl);
  const hashtags = JSON.parse(video.script.hashtags || '[]');

  let ytExternalId = `mock_yt_${Date.now()}`;
  let metaExternalId = `mock_meta_${Date.now()}`;

  if (providerMode === 'production') {
    try {
      await logToJob(jobId, `Attempting real YouTube upload...`);
      ytExternalId = await uploadToYouTube(
        absVideoPath, 
        video.script.title || video.script.topic.title,
        video.script.description || 'Generated by MovieDecoded AI',
        hashtags,
        video.script.topic.userId!
      );
      await logToJob(jobId, `YouTube upload successful. ID: ${ytExternalId}`);
    } catch (e: any) {
      await logToJob(jobId, `YouTube upload failed: ${e.message}`);
      throw e;
    }
  } else {
    await logToJob(jobId, `MOCK MODE: Simulated YouTube and Meta uploads.`);
  }

  await prisma.publication.upsert({
    where: { videoId_platform: { videoId, platform: 'YOUTUBE_SHORTS' } },
    update: { status: 'PUBLISHED', externalId: ytExternalId, publishedAt: new Date() },
    create: { videoId, platform: 'YOUTUBE_SHORTS', status: 'PUBLISHED', externalId: ytExternalId, publishedAt: new Date() }
  });

  await prisma.publication.upsert({
    where: { videoId_platform: { videoId, platform: 'INSTAGRAM_REELS' } },
    update: { status: 'PUBLISHED', externalId: metaExternalId, publishedAt: new Date() },
    create: { videoId, platform: 'INSTAGRAM_REELS', status: 'PUBLISHED', externalId: metaExternalId, publishedAt: new Date() }
  });

  await prisma.video.update({
    where: { id: videoId },
    data: { status: 'PUBLISHED' }
  });

  await prisma.script.update({
    where: { id: video.scriptId },
    data: { status: 'PUBLISHED' }
  });

  await logToJob(jobId, `Video successfully published across platforms.`);
}

import { prisma } from '../../lib/prisma';
import { logToJob, enqueueJob } from '../../lib/queue';
import { getSetting } from '../../lib/settings';
import { uploadToYouTube } from '../../lib/providers/youtube';
import path from 'path';

export async function handlePublishVideo(data: { videoId: string }, jobId: string) {
  const { videoId } = data;
  if (!videoId) throw new Error("Missing videoId");

  const video = await prisma.video.findUnique({ 
    where: { id: videoId },
    include: { script: { include: { topic: true } } }
  });

  if (!video) throw new Error(`Video ${videoId} not found`);

  // Double check approval
  const approval = await prisma.approval.findUnique({ where: { videoId } });
  if (approval?.status !== 'APPROVED') {
    throw new Error(`Cannot publish video ${videoId} because approval status is ${approval?.status}`);
  }

  await logToJob(jobId, `Starting Publishing process for video: ${video.id}`);
  
  const providerMode = await getSetting('PROVIDER_MODE');

  const absVideoPath = path.join(process.cwd(), 'public', video.fileUrl);
  const hashtags = JSON.parse(video.script.hashtags || '[]');

  let ytExternalId = `mock_yt_${Date.now()}`;
  let metaExternalId = `mock_meta_${Date.now()}`;

  // Check if a video with the exact same topic title has already been published to YouTube Shorts
  const existingPublished = await prisma.publication.findFirst({
    where: {
      platform: 'YOUTUBE_SHORTS',
      status: 'PUBLISHED',
      video: {
        id: { not: videoId },
        script: {
          topic: {
            title: {
              equals: video.script.topic.title
            }
          }
        }
      }
    }
  });

  if (existingPublished) {
    await logToJob(jobId, `A video for topic "${video.script.topic.title}" was already published on YouTube (ID: ${existingPublished.externalId}). Skipping duplicate YouTube upload to avoid repeating content on the channel.`);
    ytExternalId = existingPublished.externalId || ytExternalId;
  } else if (providerMode === 'production') {
    try {
      await logToJob(jobId, `Attempting real YouTube upload...`);
      ytExternalId = await uploadToYouTube(
        absVideoPath, 
        video.script.title || video.script.topic.title,
        video.script.description || 'Generated by MovieDecoded AI',
        hashtags,
        video.script.topic.userId!
      );
      await logToJob(jobId, `YouTube upload successful. ID: ${ytExternalId}`);
    } catch (e: any) {
      await logToJob(jobId, `YouTube upload failed: ${e.message}`);
      throw e;
    }
  } else {
    await logToJob(jobId, `MOCK MODE: Simulated YouTube and Meta uploads.`);
  }

  await prisma.publication.upsert({
    where: { videoId_platform: { videoId, platform: 'YOUTUBE_SHORTS' } },
    update: { status: 'PUBLISHED', externalId: ytExternalId, publishedAt: new Date() },
    create: { videoId, platform: 'YOUTUBE_SHORTS', status: 'PUBLISHED', externalId: ytExternalId, publishedAt: new Date() }
  });

  await prisma.publication.upsert({
    where: { videoId_platform: { videoId, platform: 'INSTAGRAM_REELS' } },
    update: { status: 'PUBLISHED', externalId: metaExternalId, publishedAt: new Date() },
    create: { videoId, platform: 'INSTAGRAM_REELS', status: 'PUBLISHED', externalId: metaExternalId, publishedAt: new Date() }
  });

  await prisma.video.update({
    where: { id: videoId },
    data: { status: 'PUBLISHED' }
  });

  await prisma.script.update({
    where: { id: video.scriptId },
    data: { status: 'PUBLISHED' }
  });

  await logToJob(jobId, `Video successfully published across platforms.`);

  // ── Auto-Pilot Loop Progression ──────────────────────────────────────────
  try {
    const autopilotStatus = await getSetting('AUTOPILOT_STATUS');
    if (autopilotStatus === 'active') {
      const remainingStr = await getSetting('AUTOPILOT_REMAINING');
      let remaining = parseInt(remainingStr, 10);
      const userId = (await getSetting('AUTOPILOT_USER_ID')) || video.script.topic.userId;

      if (userId) {
        const user = await prisma.user.findUnique({ where: { id: userId } });
        const hasCredits = user && user.credits > 0;

        // remaining = -1 means "run until credits are exhausted"
        // remaining > 1 means specific batch (e.g. 8 videos)
        const shouldContinue = Boolean(hasCredits && (remaining === -1 || remaining > 1));

        if (shouldContinue && user) {
          const nextRemaining = remaining === -1 ? -1 : remaining - 1;
          await prisma.setting.upsert({
            where: { key: 'AUTOPILOT_REMAINING' },
            update: { value: nextRemaining.toString() },
            create: { key: 'AUTOPILOT_REMAINING', value: nextRemaining.toString() }
          });

          // Deduct 1 credit for the next video
          await prisma.user.update({
            where: { id: userId },
            data: { credits: { decrement: 1 } }
          });

          const remainingMsg = nextRemaining === -1 
            ? `running continuously until credits end (${user.credits - 1} credits left)`
            : `${nextRemaining} video(s) remaining in batch`;

          await logToJob(jobId, `[AUTOPILOT] Triggering next video (${remainingMsg})...`);
          await enqueueJob('GENERATE_TOPICS', { userId, count: 1 });
        } else {
          await prisma.setting.upsert({
            where: { key: 'AUTOPILOT_STATUS' },
            update: { value: 'idle' },
            create: { key: 'AUTOPILOT_STATUS', value: 'idle' }
          });
          await prisma.setting.upsert({
            where: { key: 'AUTOPILOT_REMAINING' },
            update: { value: '0' },
            create: { key: 'AUTOPILOT_REMAINING', value: '0' }
          });
          await logToJob(jobId, `[AUTOPILOT] ✓ Auto-Pilot sequence completed! Batch target reached or credits exhausted.`);
        }
      }
    }
  } catch (err: any) {
    console.error('[AUTOPILOT] Error advancing Auto-Pilot loop:', err.message);
  }
}
